def create_cortex_m_payload(
    sp: int = 0x20010000,
    reset_vec: int = 0x08001001,
    nmi_vec: int = 0x08001021,
    hardfault_vec: int = 0x08001041,
    size: int = 128,
) -> bytes:
    """Creates a raw ARM Cortex-M vector table payload with arbitrary size."""
    table = struct.pack("<4I", sp, reset_vec, nmi_vec, hardfault_vec)
    padding = b"\x55" * max(0, size - len(table))
    return table + padding


class TestEmpiricalNestedZipEdgeCases(unittest.TestCase):
    """Stress testing recursive archive scanning across nested depths and boundary structures."""

    def setUp(self):
        self.tmpdir = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.tmpdir.cleanup()

    def test_level_4_nested_zip_with_mcu_firmware(self):
        """Firmware hidden 4 levels deep in nested ZIP archives must be blocked."""
        # Level 4: Contains prohibited MCU file
        buf4 = io.BytesIO()
        with zipfile.ZipFile(buf4, "w") as z4:
            z4.writestr("firmware/k706_mcu.bin", b"MCU_FW_BYTES")

        # Level 3: Contains Level 4
        buf3 = io.BytesIO()
        with zipfile.ZipFile(buf3, "w") as z3:
            z3.writestr("internal/fw_package.zip", buf4.getvalue())

        # Level 2: Contains Level 3
        buf2 = io.BytesIO()
        with zipfile.ZipFile(buf2, "w") as z2:
            z2.writestr("subsystem.zip", buf3.getvalue())

        # Level 1 (Outer archive)
        outer_path = os.path.join(self.tmpdir.name, "level1_outer.zip")
        with zipfile.ZipFile(outer_path, "w") as z1:
            z1.writestr("nested_core.zip", buf2.getvalue())
            z1.writestr("system.img", b"ANDROID_CLEAN")

        is_safe, viols = MCUGuard.scan_archive(outer_path, raise_on_violation=False)
        self.assertFalse(is_safe)
        self.assertTrue(len(viols) > 0)
        self.assertTrue(any("k706_mcu.bin" in v for v in viols))

    def test_nested_zip_with_uppercase_extension(self):
        """Nested ZIP archive with uppercase .ZIP extension must be inspected."""
        inner = io.BytesIO()
        with zipfile.ZipFile(inner, "w") as izf:
            izf.writestr("stm32f407.bin", b"STM32_MICROCODE")

        outer_path = os.path.join(self.tmpdir.name, "outer_upper.zip")
        with zipfile.ZipFile(outer_path, "w") as ozf:
            ozf.writestr("NESTED_PAYLOAD.ZIP", inner.getvalue())
            ozf.writestr("system.img", b"CLEAN")

        is_safe, viols = MCUGuard.scan_archive(outer_path, raise_on_violation=False)
        self.assertFalse(is_safe)
        self.assertTrue(any("stm32f407.bin" in v for v in viols))

    def test_nested_zip_with_corrupted_inner_archive(self):
        """Nested archive that is malformed/corrupted must be flagged as a safety violation."""
        outer_path = os.path.join(self.tmpdir.name, "corrupt_nested.zip")
        with zipfile.ZipFile(outer_path, "w") as ozf:
            ozf.writestr("broken_inner.zip", b"NOT_A_VALID_ZIP_HEADER_DATA")

        is_safe, viols = MCUGuard.scan_archive(outer_path, raise_on_violation=False)
        self.assertFalse(is_safe)
        self.assertTrue(any("broken_inner.zip" in v or "corrupted" in v for v in viols))

    def test_clean_nested_zip_passes(self):
        """Multiple levels of nested zip archives containing only clean Android files must pass."""
        inner = io.BytesIO()
        with zipfile.ZipFile(inner, "w") as izf:
            izf.writestr("system/build.prop", b"ro.build.version.release=10\n")
            izf.writestr("system/priv-app/Radio/Radio.apk", b"RADIO_APK_DATA")

        outer_path = os.path.join(self.tmpdir.name, "clean_outer.zip")
        with zipfile.ZipFile(outer_path, "w") as ozf:
            ozf.writestr("system.img", b"CLEAN_SYSTEM_IMAGE")
            ozf.writestr("apps/bundled_apps.zip", inner.getvalue())

        is_safe, viols = MCUGuard.scan_archive(outer_path, raise_on_violation=True)
        self.assertTrue(is_safe)
        self.assertEqual(len(viols), 0)


class TestEmpiricalUnicodeAndFAT32EdgeCases(unittest.TestCase):
    """Stress testing Unicode NFKC decomposition, fullwidth characters, spaces, and FAT32 path semantics."""

    def test_fullwidth_unicode_extensions_and_names(self):
        """Fullwidth MCU filenames like 'ｍｃｕ．ｂｉｎ' must be blocked."""
        # ｍｃｕ．ｂｉｎ
        name1 = "\uff4d\uff43\uff55\uff0e\uff42\uff49\uff4e"
        self.assertTrue(MCUGuard.is_mcu_artifact(name1))

        # ｓｔｍ３２．ｈｅｘ
        name2 = "\uff53\uff54\uff4d\uff13\uff12\uff0e\uff48\uff45\uff58"
        self.assertTrue(MCUGuard.is_mcu_artifact(name2))

        # ｇｄ３２．ｄｆｕ
        name3 = "\uff47\uff44\uff13\uff12\uff0e\uff44\uff46\uff55"
        self.assertTrue(MCUGuard.is_mcu_artifact(name3))

        # ｎ７６ｅ００３．ｂｉｎ
        name4 = "\uff4e\uff17\uff16\uff45\uff10\uff10\uff13\uff0e\uff42\uff49\uff4e"
        self.assertTrue(MCUGuard.is_mcu_artifact(name4))

    def test_mixed_fullwidth_and_ascii(self):
        """Mixed fullwidth and standard ASCII characters must be recognized."""
        # ｍcu.BIN
        name = "\uff4dcu.BIN"
        self.assertTrue(MCUGuard.is_mcu_artifact(name))

        # STM32\uff46407.bin
        name_stm = "STM32\uff46407.bin"
        self.assertTrue(MCUGuard.is_mcu_artifact(name_stm))

    def test_unicode_whitespace_and_traversal(self):
        """Ideographic spaces, tabs, and Windows backslashes must be normalized."""
        # Ideographic space \u3000 surrounding mcu.bin
        name = "\u3000\u3000firmware\\mcu.bin\u3000"
        self.assertTrue(MCUGuard.is_mcu_artifact(name))

        # Non-breaking space \u00a0
        name_nbsp = "\u00a0./sub/../k706_mcu.bin\u00a0"
        self.assertTrue(MCUGuard.is_mcu_artifact(name_nbsp))

    def test_fat32_multiple_trailing_dots_and_spaces(self):
        """FAT32 ignores trailing dots and spaces: 'mcu.bin...   ' must be blocked."""
        name = "mcu.bin...   "
        self.assertTrue(MCUGuard.is_mcu_artifact(name))

        name2 = "stm32f4.hex. . . "
        self.assertTrue(MCUGuard.is_mcu_artifact(name2))

    def test_benign_unicode_paths_pass(self):
        """Legitimate files with accented or standard characters must pass."""
        safe_names = [
            "system/media/audio/notif_été.ogg",
            "system/priv-app/Radio/Radio.apk",
            "system/fonts/NotoSans-Regular.ttf",
        ]
        for s in safe_names:
            self.assertFalse(MCUGuard.is_mcu_artifact(s))


class TestEmpiricalDisguisedVectorHeaders(unittest.TestCase):
    """Stress testing ARM Cortex-M bare-metal vector table detection across various disguised formats."""

    def setUp(self):
        self.tmpdir = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.tmpdir.cleanup()

    def test_cortex_m_boundary_sram_and_flash_addresses(self):
        """Boundary SP and Flash addresses (e.g. 0x20000000, 0x20080000, 0x08000001, 0x081fffff) must be detected."""
        # Minimum SRAM SP (0x20000000), minimum Flash Reset (0x08000001)
        p_min = create_cortex_m_payload(
            sp=0x20000000,
            reset_vec=0x08000001,
            nmi_vec=0x08000005,
            hardfault_vec=0x08000009,
        )
        self.assertTrue(MCUGuard.inspect_cortex_m_vector_table(p_min))

        # Maximum SRAM SP (0x20080000), maximum Flash Reset (0x081fffff)
        p_max = create_cortex_m_payload(
            sp=0x20080000,
            reset_vec=0x081fffff,
            nmi_vec=0x081ffffd,
            hardfault_vec=0x081ffffb,
        )
        self.assertTrue(MCUGuard.inspect_cortex_m_vector_table(p_max))

    def test_cortex_m_disguised_as_media_file_in_archive(self):
        """Vector table disguised as .wav, .ogg, .dat or without extension must be detected."""
        for ext in [".wav", ".ogg", ".dat", ".raw", ""]:
            filename = f"system/media/sound{ext}"
            zip_p = os.path.join(self.tmpdir.name, f"test_{ext.replace('.', '_')}.zip")
            with zipfile.ZipFile(zip_p, "w") as zf:
                zf.writestr(filename, create_cortex_m_payload())
                zf.writestr("system/build.prop", b"ro.build=1\n")

            is_safe, viols = MCUGuard.scan_archive(zip_p, raise_on_violation=False)
            self.assertFalse(is_safe, f"Disguised vector table in {filename} was not blocked!")
            self.assertTrue(any(filename in v for v in viols))

    def test_cortex_m_disguised_in_directory_scan(self):
        """Vector table disguised in a directory under .dat or extensionless file must be caught."""
        dir_p = os.path.join(self.tmpdir.name, "dir_test")
        os.makedirs(os.path.join(dir_p, "system", "etc"), exist_ok=True)
        target_f = os.path.join(dir_p, "system", "etc", "carrier_config.dat")
        with open(target_f, "wb") as f:
            f.write(create_cortex_m_payload())

        is_safe, viols = MCUGuard.scan_directory(dir_p, raise_on_violation=False)
        self.assertFalse(is_safe)
        self.assertTrue(any("carrier_config.dat" in v for v in viols))

    def test_non_cortex_m_legitimate_binaries_pass(self):
        """Standard non-MCU binary headers (ELF binary, Android Sparse, zeros) must pass."""
        # ELF header (magic \x7fELF)
        elf_header = b"\x7fELF" + b"\x01\x01\x01\x00" * 8
        self.assertFalse(MCUGuard.inspect_cortex_m_vector_table(elf_header))

        # Zeros
        self.assertFalse(MCUGuard.inspect_cortex_m_vector_table(b"\x00" * 64))

        # Unaligned SP (e.g. SP = 0x20010001, not 4-byte aligned)
        bad_sp = create_cortex_m_payload(sp=0x20010001)
        self.assertFalse(MCUGuard.inspect_cortex_m_vector_table(bad_sp))

        # Even reset vector (Thumb bit 0, not valid ARM Cortex-M Thumb mode)
        even_reset = create_cortex_m_payload(reset_vec=0x08001000)
        self.assertFalse(MCUGuard.inspect_cortex_m_vector_table(even_reset))


class TestEmpiricalUARTAndScriptAdversarial(unittest.TestCase):
    """Stress testing UART device nodes, case permutations, and script command variations."""

    def test_uart_variations_and_ports(self):
        """Serial device nodes (/dev/ttyS*, /dev/ttyUSB*, /dev/ttyACM*, /dev/ttyHS*, /dev/ttyMT*, /dev/ttyGS*) must all be blocked."""
        test_ports = [
            "/dev/ttys0",
            "/dev/ttyS1",
            "/dev/TTYS2",
            "/dev/ttyS10",
            "/dev/ttyusb0",
            "/dev/ttyUSB1",
            "/dev/TTYUSB2",
            "/dev/ttyacm0",
            "/dev/ttyACM1",
            "/dev/ttyhs0",
            "/dev/TTYHS1",
            "/dev/ttymt0",
            "/dev/ttyMT1",
            "/dev/ttygs0",
            "/dev/TTYGS1",
        ]
        for port in test_ports:
            cmd = f'run_program("/sbin/sh", "-c", "echo hello > {port}");\n'
            is_safe, viols = MCUGuard.check_script_content(cmd, "updater-script")
            self.assertFalse(is_safe, f"Port {port} failed to trigger safety violation!")

    def test_mcu_partition_variations_in_scripts(self):
        """Partition references (mcu, mcu_fw, mcu_app, mcu_boot, iap, stm32, gd32, nuvoton) must be blocked."""
        prohibited_targets = [
            "/dev/block/by-name/mcu",
            "/dev/block/bootdevice/by-name/mcu_fw",
            "/dev/block/by-name/mcu_app",
            "/dev/block/by-name/mcu_boot",
            "/dev/block/by-name/iap",
            "/dev/block/by-name/stm32",
            "/dev/block/by-name/gd32",
            "/dev/block/by-name/nuvoton",
            'write_raw_image("/tmp/payload", "mcu");',
            'package_extract_file("boot.img", "/dev/mcu");',
        ]
        for target in prohibited_targets:
            script = f'{target}\n'
            is_safe, viols = MCUGuard.check_script_content(script, "updater-script")
            self.assertFalse(is_safe, f"Partition target '{target}' bypassed script inspection!")

    def test_prohibited_script_flashing_tools(self):
        """Script commands invoking stm32flash, mcu_update, or flash_mcu must be blocked."""
        commands = [
            "stm32flash -w payload.bin /dev/ttyS0",
            "STM32FLASH -w payload.bin /dev/ttyS1",
            "mcu_update /tmp/mcu.bin",
            "flash_mcu --force /sdcard/fw.bin",
        ]
        for cmd in commands:
            script = f'#!/system/bin/sh\n{cmd}\n'
            is_safe, viols = MCUGuard.check_script_content(script, "post_install.sh")
            self.assertFalse(is_safe, f"Script command '{cmd}' was not blocked!")

    def test_clean_updater_script_with_android_partitions_passes(self):
        """Legitimate Edify commands targeting Android partitions must be approved."""
        script = (
            'ui_print("Debloat OS QF001 Installation...");\n'
            'package_extract_file("boot.img", "/dev/block/by-name/boot");\n'
            'package_extract_file("super.img", "/dev/block/by-name/super");\n'
            'package_extract_file("system.img", "/dev/block/by-name/system");\n'
            'package_extract_file("vendor.img", "/dev/block/by-name/vendor");\n'
            'set_progress(1.0);\n'
        )
        is_safe, viols = MCUGuard.check_script_content(script, "updater-script")
        self.assertTrue(is_safe)
        self.assertEqual(len(viols), 0)


class TestEmpiricalEndToEndArchiveAudit(unittest.TestCase):
    """Full realistic end-to-end audit for clean and adversarial update.zip packages."""

    def setUp(self):
        self.tmpdir = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.tmpdir.cleanup()

    def test_e2e_clean_production_update_zip(self):
        """Simulate a full production debloated update.zip and assert strict approval."""
        zip_path = os.path.join(self.tmpdir.name, "clean_production_update.zip")
        with zipfile.ZipFile(zip_path, "w") as zf:
            zf.writestr("system.img", b"SPARSE_SYSTEM_DATA")
            zf.writestr("boot.img", b"BOOT_KERNEL_DATA")
            zf.writestr("vendor.img", b"VENDOR_BLOBS_DATA")
            zf.writestr(
                "META-INF/com/google/android/updater-script",
                'ui_print("Installing QF001 Debloat OS...");\n'
                'package_extract_file("boot.img", "/dev/block/by-name/boot");\n'
                'package_extract_file("system.img", "/dev/block/by-name/system");\n',
            )
            zf.writestr("META-INF/com/android/metadata", b"post-build=1\n")
            zf.writestr("system/priv-app/IOSLauncher/IOSLauncher.apk", b"APK_DATA")
            zf.writestr("system/priv-app/Radio/Radio.apk", b"RADIO_DATA")

        is_safe, viols = MCUGuard.scan_archive(zip_path, raise_on_violation=True)
        self.assertTrue(is_safe)
        self.assertEqual(len(viols), 0)

    def test_e2e_multi_threat_adversarial_zip_blocked(self):
        """An archive containing multiple concurrent attack vectors must trigger MCUSafetyViolationError."""
        zip_path = os.path.join(self.tmpdir.name, "multi_threat.zip")

        # Nested zip with disguised vector table
        inner_buf = io.BytesIO()
        with zipfile.ZipFile(inner_buf, "w") as izf:
            izf.writestr("driver.dat", create_cortex_m_payload())

        with zipfile.ZipFile(zip_path, "w") as zf:
            zf.writestr("system.img", b"SYSTEM")
            # Attack vector 1: Fullwidth MCU filename
            zf.writestr("\uff4d\uff43\uff55.bin", b"MCU_FW")
            # Attack vector 2: Nested archive with vector header
            zf.writestr("nested/drivers.zip", inner_buf.getvalue())
            # Attack vector 3: Script with UART writing
            zf.writestr(
                "META-INF/com/google/android/updater-script",
                'run_program("/sbin/sh", "-c", "cat fw > /dev/ttyS0");\n',
            )

        with self.assertRaises(MCUSafetyViolationError) as ctx:
            MCUGuard.scan_archive(zip_path, raise_on_violation=True)

        self.assertTrue(len(ctx.exception.violations) >= 3)


